/// <reference types="vitest/config" />
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { svelte } from "@sveltejs/vite-plugin-svelte";
import { type Plugin, type PluginOption, defineConfig } from "vite";

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

/**
 * Writes sw.js for the build: it caches every file of the app when it installs, so the installed app (or a page
 * visited once) works offline. A new build changes the cache name; the previous version's files are kept until the
 * next update, for pages of that version still open (they start their simulation workers later).
 */
function offline(): Plugin {
  const publicDir = fileURLToPath(new URL("./public", import.meta.url));
  return {
    name: "calcbj-offline",
    apply: "build",
    generateBundle(_options, bundle) {
      const hash = createHash("sha256");
      const publicFiles = listFiles(publicDir).map((path) => {
        hash.update(readFileSync(path));
        return relative(publicDir, path).split("\\").join("/");
      });
      const files = [...new Set(["index.html", ...Object.keys(bundle), ...publicFiles])].filter((f) => f !== "sw.js").sort();
      for (const item of Object.values(bundle)) hash.update(item.type === "chunk" ? item.code : item.source);
      const version = hash.digest("hex").slice(0, 12);
      const urls = ["./", ...files.map((f) => "./" + f)];
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: `// CalcBJ offline support, generated by vite.config.ts.
const CACHE = "calcbj-${version}";
const FILES = ${JSON.stringify(urls)};
// Hosts may send "Vary: Origin", and module scripts are requested with an Origin header the cached copies lack.
const MATCH = { ignoreVary: true };

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  // Cache names come back oldest first: all but the newest older version go.
  event.waitUntil(
    caches
      .keys()
      .then((keys) => keys.filter((k) => k.startsWith("calcbj-") && k !== CACHE).slice(0, -1))
      .then((old) => Promise.all(old.map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

/** The page itself: from the network so updates arrive; from the cache when offline or after 3 s without an answer. */
function page(request) {
  const network = fetch(request);
  const cached = () => caches.open(CACHE).then((cache) => cache.match("./", MATCH));
  const slow = new Promise((resolve) => setTimeout(resolve, 3000)).then(cached).then((hit) => hit || network);
  return Promise.race([network, slow]).catch(() => cached().then((hit) => hit || Response.error()));
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === "navigate") {
    event.respondWith(page(request));
    return;
  }
  // This version's copy, then an older version's (a page opened before an update), then the network.
  event.respondWith(
    caches
      .open(CACHE)
      .then((cache) => cache.match(request, MATCH))
      .then((hit) => hit || caches.match(request, MATCH))
      .then((hit) => hit || fetch(request)),
  );
});
`,
      });
    },
  };
}

/**
 * The iPhone app's viewport: without a maximum scale, iOS zooms in on every field whose text is smaller than 16 px
 * when it gets the focus, and the app has no use for pinch zoom. The web app keeps its viewport (and zoom).
 */
function iphoneViewport(): Plugin {
  return {
    name: "calcbj-iphone-viewport",
    transformIndexHtml(html) {
      const out = html.replace(/(<meta name="viewport" content=")([^"]*)"/, '$1$2, maximum-scale=1"');
      if (out === html) throw new Error("index.html has no viewport meta tag to change");
      return out;
    },
  };
}

export default defineConfig(({ mode }) => {
  // Mode "desktop" builds the pages for the desktop app, "android" and "ios" for the phone apps (all in src-tauri).
  // The apps have their files inside, so they get no offline cache.
  const mobile = mode === "android" || mode === "ios";
  const app = mode === "desktop" || mobile;
  // "tauri android dev" / "tauri ios dev" on a real phone load the dev server over the network from this address.
  const devHost = process.env.TAURI_DEV_HOST;
  const plugins: PluginOption[] = [svelte()];
  if (!app) plugins.push(offline());
  if (mode === "ios") plugins.push(iphoneViewport());
  return {
    // Relative asset paths, so the built app works from any folder of a static host.
    base: "./",
    plugins,
    define: {
      __DESKTOP__: JSON.stringify(mode === "desktop"),
      __MOBILE__: JSON.stringify(mobile),
      __ANDROID__: JSON.stringify(mode === "android"),
      __IOS__: JSON.stringify(mode === "ios"),
    },
    worker: { format: "es" },
    // The unit tests (npm test, tests/*.test.ts) run Svelte's browser code on a jsdom page, which has localStorage and
    // DOMParser.
    resolve: process.env.VITEST ? { conditions: ["browser"] } : undefined,
    test: { environment: "jsdom", include: ["tests/**/*.test.ts"] },
    // The iPhone app supports iOS 16 (src-tauri/tauri.ios.conf.json), whose WebKit lacks a few ES2022 features.
    build: { target: mode === "ios" ? ["es2022", "safari16"] : "es2022" },
    server: {
      port: 5173,
      strictPort: true,
      host: devHost || false,
      hmr: devHost ? { protocol: "ws", host: devHost, port: 5174 } : undefined,
    },
  };
});
