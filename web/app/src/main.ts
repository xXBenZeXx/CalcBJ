import "./app.css";
import { mount } from "svelte";
import { loadEngine } from "./lib/engine/engine";

const target = document.getElementById("app") as HTMLElement;

try {
  await loadEngine();
  // The app's state reads the engine as soon as it loads, so it is imported once the engine is ready.
  const { default: App } = await import("./App.svelte");
  mount(App, { target });
  // Test hook for the dev server only (scenario files without the file picker); not in the built app.
  if (import.meta.env.DEV) Object.assign(window, { calcbj: await import("./lib/files") });
} catch (e) {
  const p = document.createElement("p");
  p.className = "startup-error";
  p.textContent = "CalcBJ could not start: " + (e instanceof Error ? e.message : String(e));
  target.replaceChildren(p);
}

// Offline support and installing (the built web app only; sw.js is generated by vite.config.ts, and the desktop app
// has its files inside).
if (import.meta.env.PROD && !__DESKTOP__ && "serviceWorker" in navigator) {
  navigator.serviceWorker.register("./sw.js").catch(() => {
    // Needs https (or localhost); without it the app still works online.
  });
}
